-- 2. レベルなしの既存語を Level 4 に
UPDATE public.words w SET level = 4
FROM v11_level4 v
WHERE w.thai = v.thai AND (w.level IS NULL OR w.level = 0);

-- 3. 読みが空の既存語に読みを入れる
UPDATE public.words w SET reading = v.reading
FROM v11_level4 v
WHERE w.thai = v.thai AND coalesce(trim(w.reading), '') = '';

-- 1. 辞書にない語を追加
INSERT INTO public.words (thai, japanese, reading, level)
SELECT v.thai, v.japanese, v.reading, 4
FROM v11_level4 v
WHERE NOT EXISTS (SELECT 1 FROM public.words w WHERE w.thai = v.thai);

